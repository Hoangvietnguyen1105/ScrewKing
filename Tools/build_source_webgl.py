"""Compile shipped source into a static jslib factory; never evaluate downloaded code."""
from pathlib import Path
import hashlib,json
root=Path(__file__).resolve().parents[1]
source=root/'Assets/ScrewKing/Resources/Source'
parts={n:(source/(n+'.js.txt')).read_text() for n in ['CocosPhysics','CocosRules','Bridge']}
assert parts['CocosPhysics'].count('this.__engineRequire=n')==1
physics=parts['CocosPhysics'].replace('this.__engineRequire=n','scope.__engineRequire=n')
factory='function () {\nvar scope=this;\n'+physics+'\nvar __engineRequire=scope.__engineRequire;\n'+parts['CocosRules']+'\n'+parts['Bridge']+'''
return {Generate:SourceGenerate,Pick:SourcePick,ResetPhysics:SourcePhysicsReset,
 AddBoard:SourceBoardAdd,ShowBoard:SourceBoardVisible,Dynamic:SourceBoardDynamic,
 Release:SourceRelease,Remove:SourceBoardRemove,Step:SourcePhysicsStep,Covers:SourceCovers};
}'''
js='''// Generated by Tools/build_source_webgl.py. Do not edit by hand.
mergeInto(LibraryManager.library, {
 $ScrewKingSource: {
  next: 1, instances: {},
  create: function () {
   var scope={};
   var api=('''+factory+''').call(scope);
   var id=ScrewKingSource.next++; ScrewKingSource.instances[id]=api; return id;
  },
  call: function(id,operation,args) {
   try {
    var api=ScrewKingSource.instances[id];
    if(!api || !Object.prototype.hasOwnProperty.call(api,operation)) throw new Error('Invalid source operation: '+operation);
    var result=api[operation].apply(null,JSON.parse(args));
    return JSON.stringify({ok:true,value:String(result)});
   } catch(error) {return JSON.stringify({ok:false,error:String(error && error.stack || error)});}
  }
 },
 SKSourceCreate__deps: ['$ScrewKingSource'],
 SKSourceCreate: function() { return ScrewKingSource.create(); },
 SKSourceCall__deps: ['$ScrewKingSource'],
 SKSourceCall: function(id,op,args) {
  var result=ScrewKingSource.call(id,UTF8ToString(op),UTF8ToString(args));
  var bytes=lengthBytesUTF8(result)+1, pointer=_malloc(bytes);
  stringToUTF8(result,pointer,bytes); return pointer;
 },
 SKSourceFree: function(pointer) {_free(pointer);},
 SKSourceDestroy__deps: ['$ScrewKingSource'],
 SKSourceDestroy: function(id) {delete ScrewKingSource.instances[id];}
});
'''
(root/'Assets/Plugins/WebGL/ScrewKingSource.jslib').write_text(js)
(root/'Tools/source-webgl-fingerprints.json').write_text(json.dumps({n:hashlib.sha256(v.encode()).hexdigest() for n,v in parts.items()},indent=2)+'\n')
print('Generated static source bridge:',len(js),'bytes')
